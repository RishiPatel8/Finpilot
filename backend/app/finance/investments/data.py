def get_product_by_id(product_id: str) -> Dict[str, Any]:
    for p in INDIAN_INVESTMENT_PRODUCTS:
        if p["id"] == product_id:
            return p
    # Fallback to bank_fd if not found
    return INDIAN_INVESTMENT_PRODUCTS[5]


def filter_products(
    category: str = "all",
    max_risk: str = "all",
    only_guaranteed: bool = False,
    max_lock_in_months: int = 999
) -> List[Dict[str, Any]]:
    results = []
    for p in INDIAN_INVESTMENT_PRODUCTS:
        if category != "all" and p["category"] != category:
            continue
        if only_guaranteed and p["rate_type"] != "guaranteed":
            continue
        if p["lock_in_months"] > max_lock_in_months:
            continue
        results.append(p)
    return results
